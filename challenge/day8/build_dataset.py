def row(task, split, user, assistant, needles, extra=None):
    item = {
        "task": task,
        "split": split,
        "needles": needles,
        "messages": [
            {"role": "user", "content": user},
            {"role": "assistant", "content": assistant},
        ],
    }
    if extra:
        item.update(extra)
    return item


def format_answer(text):
    return f"ОТВЕТ: {text}\nКОНЕЦ"


def style_answer(sentence):
    return f"Пишу я, Еремей Сухой. {sentence} Аминь чернилам."


def main():
    DATA.mkdir(parents=True, exist_ok=True)
    train, valid, close, far = [], [], [], []
    seen = set()

    def take(bucket, item):
        text = item["messages"][0]["content"]
        if text in seen:
            raise SystemExit(f"повтор вопроса: {text}")
        seen.add(text)
        bucket.append(item)

    for fact in FACTS:
        for question in fact["train"]:
            take(train, row("fact", "train", question, fact["answer"], fact["needles"], {"fact_id": fact["id"]}))
        take(valid, row("fact", "valid", fact["valid"], fact["answer"], fact["needles"], {"fact_id": fact["id"]}))
        take(close, row("fact", "close", fact["close"], fact["answer"], fact["needles"], {"fact_id": fact["id"]}))
        take(far, row("fact", "far", fact["far"], fact["answer"], fact["needles"], {"fact_id": fact["id"]}))

    for question, answer in FORMAT:
        take(train, row("format", "train", question, format_answer(answer), [answer.casefold()]))
    for question, answer in FORMAT_VALID:
        take(valid, row("format", "valid", question, format_answer(answer), [answer.casefold()]))
    for question, answer in FORMAT_EVAL:
        take(close, row("format", "close", question, format_answer(answer), [answer.casefold()]))

    for sentence in STYLE_TRAIN:
        take(train, row("style", "train", f"Перескажи по-летописному: {sentence}", style_answer(sentence), [sentence.casefold()]))
    for sentence in STYLE_VALID:
        take(valid, row("style", "valid", f"Перескажи по-летописному: {sentence}", style_answer(sentence), [sentence.casefold()]))
    for cue, sentence in STYLE_EVAL:
        take(close, row("style", "close", f"{cue} {sentence}", style_answer(sentence), [sentence.casefold()]))

    ood = []
    for key, question, needles in OOD:
        if question in seen:
            raise SystemExit(f"ood пересекся с обучением: {question}")
        ood.append(row("ood", "ood", question, "", needles, {"ood_id": key}))

    def write(name, rows):
        prefix = name.removesuffix(".jsonl")
        for index, item in enumerate(rows, start=1):
            item["id"] = f"{prefix}-{index:03d}"
        text = "\n".join(json.dumps(item, ensure_ascii=False) for item in rows) + "\n"
        (DATA / name).write_text(text, encoding="utf-8")

    write("train.jsonl", train)
    write("valid.jsonl", valid)
    write("eval_close.jsonl", close)
    write("eval_far.jsonl", far)
    write("eval_ood.jsonl", ood)
    stats = {
        "train": len(train),
        "valid": len(valid),
        "eval_close": len(close),
        "eval_far": len(far),
        "ood": len(ood),
        "by_task_train": {task: sum(1 for item in train if item["task"] == task) for task in ("fact", "format", "style")},
    }
    (DATA / "stats.json").write_text(json.dumps(stats, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(stats, ensure_ascii=False))


if __name__ == "__main__":
    main()
